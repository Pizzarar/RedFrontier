#!/usr/bin/env python3
"""Generate the owner's walk sheet (world-04 N) into OWNER-TESTS.md.

One section per ENABLED region, listing every unverified place in the real fh_tour order. The order comes from
FhPlaceResolver.tour evaluated under lupa over the real configs (never reimplemented here).

  ~/.venvs/rf/bin/python tools/world-walk-sheet.py            rewrite the marked block in OWNER-TESTS.md
  ~/.venvs/rf/bin/python tools/world-walk-sheet.py --check    exit 1 if the file is out of date (no write)

Only the text between the BEGIN/END markers is owned; the rest of the file is left byte-identical. If the markers
are absent the block is appended at the end. Idempotent: a second run changes nothing.
"""
import os
import sys

VENV_PY = os.path.expanduser('~/.venvs/rf/bin/python')
try:
    from lupa import lua54 as lupa_mod
except ImportError:
    if os.path.exists(VENV_PY) and not os.environ.get('RF_SPECS_REEXEC'):
        os.environ['RF_SPECS_REEXEC'] = '1'
        os.execv(VENV_PY, [VENV_PY] + sys.argv)
    sys.exit(f'world-walk-sheet: needs lupa 2.x (use {VENV_PY})')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FH = ROOT + '/server/resources/[fh]/'
DOC = os.path.join(ROOT, 'OWNER-TESTS.md')
BEGIN = '<!-- BEGIN world-walk-sheet (generated by tools/world-walk-sheet.py; do not edit by hand) -->'
END = '<!-- END world-walk-sheet -->'

LUA = r'''
return function(root)
    local fh = root .. '/server/resources/[fh]/'
    package.path = fh .. 'fh_core/?.lua;' .. fh .. 'fh_core/shared/?.lua;' .. package.path
    vector3 = function(x, y, z) return { x = x, y = y, z = z } end
    vector4 = function(x, y, z, w) return { x = x, y = y, z = z, w = w } end
    local Regions = require('regions')
    _G.FhRegions = Regions
    _G.FhPlaceResolver = require('place_resolver')
    dofile(fh .. 'fh_homestead/config.lua')
    dofile(fh .. 'fh_zones/config.lua')
    dofile(fh .. 'fh_trade/config.lua')
    local P = _G.FhPlaceResolver
    local places = P.index(Regions, { homestead = _G.FhHomesteadConfig, zones = _G.FhZonesConfig })
    local ids = {}
    for id in pairs(Regions.regions) do if Regions.isEnabled(id) then ids[#ids + 1] = id end end
    table.sort(ids)
    local out = {}
    for _, id in ipairs(ids) do
        local r = Regions.regions[id]
        local rows = {}
        for _, p in ipairs(P.tour(places, id)) do
            rows[#rows + 1] = table.concat({ p.id, p.label or '', p.kind, p.class or '' }, '\t')
        end
        local origin = ''
        for _, p in ipairs(places) do if p.kind == 'town' and p.region == id then origin = p.id; break end end
        out[#out + 1] = id .. '\t' .. (r.label or r.name or id) .. '\t' .. origin .. '\n' .. table.concat(rows, '\n')
    end
    return table.concat(out, '\n@@\n')
end
'''

CHECKS = {
    'claim': 'Ground: is the claim center on flat, open ground (not floating, buried or on a slope)? '
             'Is it reachable by horse and not inside a building, water or a rock? Does the chest/blip sit on the ground?',
    'lot': 'Ground: is the lot flat and on the town street/plot (not in a building, road or water)? '
           'Reachable on foot and by horse? Clear of other lots?',
    'camp': 'Ground: flat and reachable by horse? Not in a building? Is the camp out of sight of the road '
            '(not visible from the main trail)? Room for the stash and four peds on the ground?',
    'post': 'Ground: on flat ground beside the town, reachable by horse, not inside a building? '
            'Does the prompt sit at ground level?',
    'town': 'Ground: the spot is on the street, flat and reachable.',
    'ambush': 'Ground: flat, reachable by horse, not in a building, and with sight lines onto the road?',
}


def region_data():
    lua = lupa_mod.LuaRuntime(unpack_returned_tuples=True)
    raw = lua.execute(LUA)(ROOT.replace(os.sep, '/'))
    regions = []
    for chunk in raw.split('\n@@\n') if raw else []:
        head, _, body = chunk.partition('\n')
        rid, name, origin = head.split('\t')
        rows = [ln.split('\t') for ln in body.split('\n') if ln]
        regions.append((rid, name, origin, rows))
    return regions


def render(regions):
    out = [BEGIN, '', '## World-04: walk sheets (generated)', '',
           'Regenerate with `~/.venvs/rf/bin/python tools/world-walk-sheet.py`. Places are listed in the real `fh_tour`',
           'order (each region starts from its first town, which is the origin and not listed). In game: `fh_tour <region>`,',
           'then `fh_tour next` for each stop; at each one run `fh_mark ok`, or `fh_mark bad <note>` naming the fix.',
           'Verdicts append to `world_walk.json` (fh_core resource folder, never committed). `fh_tp <placeId>` jumps to any id.',
           '']
    for rid, name, origin, rows in regions:
        out.append(f'### {name} (`{rid}`) - {len(rows)} unverified place(s)')
        out.append('')
        out.append(f'Start: `fh_tour {rid}`' + (f' (origin town `{origin}`)' if origin else ''))
        out.append('')
        if not rows:
            out.append('Nothing unverified.')
            out.append('')
            continue
        for i, (pid, label, kind, cls) in enumerate(rows, 1):
            out.append(f'{i}. [ ] `{pid}` - {label or pid} ({kind})')
            out.append(f'   {CHECKS.get(kind, CHECKS["claim"])}')
            out.append('   RESULT:')
        out.append('')
    out.append(END)
    return '\n'.join(out)


def apply(text, block):
    a, b = text.find(BEGIN), text.find(END)
    if a != -1 and b > a:
        return text[:a] + block + text[b + len(END):]
    sep = '' if text.endswith('\n\n') else ('\n' if text.endswith('\n') else '\n\n')
    return text + sep + block + '\n'


def main(argv):
    block = render(region_data())
    with open(DOC, encoding='utf-8', newline='') as f:
        old = f.read()
    new = apply(old, block)
    if '--check' in argv:
        return 0 if new == old else 1
    if new != old:
        with open(DOC, 'w', encoding='utf-8', newline='') as f:
            f.write(new)
        print('world-walk-sheet: updated OWNER-TESTS.md')
    else:
        print('world-walk-sheet: no change')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
