local here = debug.getinfo(1, 'S').source:match('^@(.*[/\\])') or './'
local T = dofile(here .. 'support/fh_prelude.lua')
local describe, it, eq, same = T.describe, T.it, T.eq, T.same

local config = require('config')
local Items = require('items')

config.Items = {
    gold_bar = { label = 'Gold Bar', weight = 12000, size_class = 'cargo', stackable = true, value_base = 500, illicit = true },
}
config.ItemOverrides = {
    saddle = { size_class = 'bulky', value_base = 40 },
    gold_bar = { illicit = false }, -- an override wins over the full definition, even when false
}

describe('fh_core shared/items', function()
    describe('validate', function()
        it('accepts a full definition', function()
            assert(Items.validate({ label = 'Rope', weight = 300, size_class = 'pocket', value_base = 2 }))
        end)
        it('rejects an unknown size class', function()
            local ok, err = Items.validate({ label = 'X', weight = 1, size_class = 'huge' })
            eq(false, ok); eq('fh_bad_size_class', err)
        end)
        it('rejects negative value_base and weight', function()
            eq('fh_bad_value_base', select(2, Items.validate({ label = 'X', weight = 1, value_base = -1 })))
            eq('fh_bad_weight', select(2, Items.validate({ label = 'X', weight = -5 })))
        end)
        it('rejects non-boolean illicit / stackable', function()
            eq('fh_bad_illicit', select(2, Items.validate({ label = 'X', weight = 1, illicit = 'yes' })))
            eq('fh_bad_stackable', select(2, Items.validate({ label = 'X', weight = 1, stackable = 1 })))
        end)
        it('needs label and weight unless partial', function()
            eq('fh_bad_label', select(2, Items.validate({ weight = 1 })))
            assert(Items.validate({ size_class = 'bulky' }, true))
        end)
    end)

    describe('define', function()
        it('registers a runtime definition that resolve finds', function()
            Items._reset()
            assert(Items.define('lockbox', { label = 'Lockbox', weight = 9000, size_class = 'cargo', stackable = false }))
            local def = Items.resolve('lockbox')
            eq('cargo', def.size_class); eq(false, def.stackable); eq(false, def.fast_travel)
            Items._reset()
            eq(nil, Items.resolve('lockbox'))
        end)
        it('refuses an invalid definition', function()
            local ok, err = Items.define('bad', { label = 'Bad', weight = 1, size_class = 'nope' })
            eq(false, ok); eq('fh_bad_size_class', err)
        end)
    end)

    describe('resolve', function()
        it('defaults an rsg item to pocket, value 0, legal, stackable unless unique', function()
            local def = Items.resolve('bread', { name = 'bread', label = 'Bread', weight = 100, unique = false })
            same({ name = 'bread', label = 'Bread', weight = 100, size_class = 'pocket', stackable = true,
                value_base = 0, illicit = false, fast_travel = true }, def)
            eq(false, Items.resolve('pistol', { weight = 1000, unique = true }).stackable)
        end)
        it('layers ItemOverrides over the rsg item', function()
            local def = Items.resolve('saddle', { label = 'Saddle', weight = 5000, unique = true })
            eq('bulky', def.size_class); eq(40, def.value_base); eq(5000, def.weight); eq(false, def.stackable)
        end)
        it('uses the full fh definition, with the override winning even when false', function()
            local def = Items.resolve('gold_bar')
            eq('cargo', def.size_class); eq(12000, def.weight); eq(500, def.value_base)
            eq(false, def.illicit); eq(false, def.fast_travel)
        end)
        it('returns fh_unknown_item with no definition and no rsg item', function()
            local def, err = Items.resolve('nothing_here')
            eq(nil, def); eq('fh_unknown_item', err)
        end)
    end)

    describe('instance fields', function()
        it('treats missing condition/stars as nil (old saves are not rejected)', function()
            eq(nil, Items.condition({ name = 'x' })); eq(nil, Items.stars({ name = 'x', info = {} }))
        end)
        it('clamps condition to 0-100 and stars to 1-3', function()
            eq(100, Items.condition({ info = { condition = 140 } }))
            eq(0, Items.condition({ info = { condition = -2 } }))
            eq(55, Items.condition({ info = { condition = 55 } }))
            eq(3, Items.stars({ info = { stars = 7 } }))
            eq(1, Items.stars({ info = { stars = 0 } }))
            eq(2, Items.stars({ info = { stars = 2.2 } }))
        end)
        it('does not read info.quality (rsg freshness) as stars', function()
            eq(nil, Items.stars({ info = { quality = 80 } }))
        end)
    end)

    describe('toRsg', function()
        it('builds an RSGCore.Shared.Items entry', function()
            local e = Items.toRsg('gold_bar', config.Items.gold_bar)
            eq('gold_bar', e.name); eq('Gold Bar', e.label); eq(12000, e.weight); eq('item', e.type)
            eq('gold_bar.png', e.image); eq(false, e.unique); eq('cargo', e.size_class); eq(true, e.illicit)
        end)
        it('keeps the existing rsg keys and layers fh keys on top', function()
            local e = Items.toRsg('saddle', { size_class = 'bulky', value_base = 40 },
                { name = 'saddle', label = 'Saddle', weight = 5000, unique = true, image = 'saddle_x.png', useable = true })
            eq('Saddle', e.label); eq('saddle_x.png', e.image); eq(true, e.unique); eq(true, e.useable)
            eq('bulky', e.size_class); eq(40, e.value_base)
        end)
    end)
end)

T.finish()
