local here = debug.getinfo(1, 'S').source:match('^@(.*[/\\])') or './'
local T = dofile(here .. 'support/fh_prelude.lua')
local describe, it, eq, same = T.describe, T.it, T.eq, T.same

local config = require('config')
local Items = require('items')

config.Items = {
    gold_bar = { label = 'Gold Bar', weight = 12000, size_class = 'cargo', stackable = true, value_base = 500, illicit = true },
}
config.ItemOverrides = {
    saddle = { size_class = 'bulky', value_base = 40 },
    gold_bar = { illicit = false }, -- an override wins over the full definition, even when false
}

describe('fh_core shared/items', function()
    describe('validate', function()
        it('accepts a full definition', function()
            assert(Items.validate({ label = 'Rope', weight = 300, size_class = 'pocket', value_base = 2 }))
        end)
        it('rejects an unknown size class', function()
            local ok, err = Items.validate({ label = 'X', weight = 1, size_class = 'huge' })
            eq(false, ok); eq('fh_bad_size_class', err)
        end)
        it('rejects negative value_base and weight', function()
            eq('fh_bad_value_base', select(2, Items.validate({ label = 'X', weight = 1, value_base = -1 })))
            eq('fh_bad_weight', select(2, Items.validate({ label = 'X', weight = -5 })))
        end)
        it('rejects non-boolean illicit / stackable', function()
            eq('fh_bad_illicit', select(2, Items.validate({ label = 'X', weight = 1, illicit = 'yes' })))
            eq('fh_bad_stackable', select(2, Items.validate({ label = 'X', weight = 1, stackable = 1 })))
        end)
        it('needs label and weight unless partial', function()
            eq('fh_bad_label', select(2, Items.validate({ weight = 1 })))
            assert(Items.validate({ size_class = 'bulky' }, true))
        end)
    end)

    describe('define', function()
        it('registers a runtime definition that resolve finds', function()
            Items._reset()
            assert(Items.define('lockbox', { label = 'Lockbox', weight = 9000, size_class = 'cargo', stackable = false }))
            local def = Items.resolve('lockbox')
            eq('cargo', def.size_class); eq(false, def.stackable); eq(false, def.fast_travel)
            Items._reset()
            eq(nil, Items.resolve('lockbox'))
        end)
        it('refuses an invalid definition', function()
            local ok, err = Items.define('bad', { label = 'Bad', weight = 1, size_class = 'nope' })
            eq(false, ok); eq('fh_bad_size_class', err)
        end)
    end)

    describe('resolve', function()
        it('defaults an rsg item to pocket, value 0, legal, stackable unless unique', function()
            local def = Items.resolve('bread', { name = 'bread', label = 'Bread', weight = 100, unique = false })
            same({ name = 'bread', label = 'Bread', weight = 100, size_class = 'pocket', stackable = true,
                value_base = 0, illicit = false, fast_travel = true }, def)
            eq(false, Items.resolve('pistol', { weight = 1000, unique = true }).stackable)
        end)
        it('layers ItemOverrides over the rsg item', function()
            local def = Items.resolve('saddle', { label = 'Saddle', weight = 5000, unique = true })
            eq('bulky', def.size_class); eq(40, def.value_base); eq(5000, def.weight); eq(false, def.stackable)
        end)
        it('uses the full fh definition, with the override winning even when false', function()
            local def = Items.resolve('gold_bar')
            eq('cargo', def.size_class); eq(12000, def.weight); eq(500, def.value_base)
            eq(false, def.illicit); eq(false, def.fast_travel)
        end)
        it('returns fh_unknown_item with no definition and no rsg item', function()
            local def, err = Items.resolve('nothing_here')
            eq(nil, def); eq('fh_unknown_item', err)
        end)
    end)

    describe('instance fields', function()
        it('treats missing condition/stars as nil (old saves are not rejected)', function()
            eq(nil, Items.condition({ name = 'x' })); eq(nil, Items.stars({ name = 'x', info = {} }))
        end)
        it('clamps condition to 0-100 and stars to 1-3', function()
            eq(100, Items.condition({ info = { condition = 140 } }))
            eq(0, Items.condition({ info = { condition = -2 } }))
            eq(55, Items.condition({ info = { condition = 55 } }))
            eq(3, Items.stars({ info = { stars = 7 } }))
            eq(1, Items.stars({ info = { stars = 0 } }))
            eq(2, Items.stars({ info = { stars = 2.2 } }))
        end)
        it('does not read info.quality (rsg freshness) as stars', function()
            eq(nil, Items.stars({ info = { quality = 80 } }))
        end)
    end)

    describe('toRsg', function()
        it('builds an RSGCore.Shared.Items entry', function()
            local e = Items.toRsg('gold_bar', config.Items.gold_bar)
            eq('gold_bar', e.name); eq('Gold Bar', e.label); eq(12000, e.weight); eq('item', e.type)
            eq('gold_bar.png', e.image); eq(false, e.unique); eq('cargo', e.size_class); eq(true, e.illicit)
        end)
        it('keeps the existing rsg keys and layers fh keys on top', function()
            local e = Items.toRsg('saddle', { size_class = 'bulky', value_base = 40 },
                { name = 'saddle', label = 'Saddle', weight = 5000, unique = true, image = 'saddle_x.png', useable = true })
            eq('Saddle', e.label); eq('saddle_x.png', e.image); eq(true, e.unique); eq(true, e.useable)
            eq('bulky', e.size_class); eq(40, e.value_base)
        end)
    end)
    describe('resolve: rsg-side fallback for runtime-registered items', function()
        it('reads size_class/value_base/illicit from the passed rsg item when fh has no entry', function()
            local def = Items.resolve('crate_rt', { name = 'crate_rt', label = 'Crate', weight = 9000, unique = true,
                size_class = 'cargo', value_base = 75, illicit = true })
            same({ name = 'crate_rt', label = 'Crate', weight = 9000, size_class = 'cargo', stackable = false,
                value_base = 75, illicit = true, fast_travel = false }, def)
        end)
        it('reads them through sharedLookup when only a name (or a bare inventory item) is given', function()
            local shared = { crate_rt = { name = 'crate_rt', label = 'Crate', weight = 9000, unique = false,
                size_class = 'bulky', value_base = 5 } }
            Items.sharedLookup = function(n) return shared[n] end
            local ok, err = pcall(function()
                eq('bulky', Items.resolve('crate_rt').size_class, 'by name')
                eq(5, Items.resolve('crate_rt').value_base, 'value by name')
                -- an inventory item copies label/weight/unique but not the fh fields
                eq('bulky', Items.resolve('crate_rt', { name = 'crate_rt', weight = 9000, amount = 1 }).size_class)
                eq('fh_unknown_item', select(2, Items.resolve('nope_rt')))
            end)
            Items.sharedLookup = nil
            assert(ok, err)
        end)
        it('fh config still wins over the rsg fields, and junk rsg fields are refused or ignored', function()
            eq('cargo', Items.resolve('gold_bar', { name = 'gold_bar', size_class = 'pocket' }).size_class)
            eq('bulky', Items.resolve('saddle', { name = 'saddle', size_class = 'cargo' }).size_class)
            eq('fh_bad_size_class', select(2, Items.resolve('odd_rt', { name = 'odd_rt', size_class = 'huge' })))
            local def = Items.resolve('odd_rt', { name = 'odd_rt', illicit = 'yes', value_base = 'x' })
            eq(false, def.illicit); eq(0, def.value_base); eq('pocket', def.size_class)
        end)
    end)
end)

describe('register (B7: runtime registerItems from sibling resources)', function()
    local base = { bread = true } -- a base rsg item
    local function isBase(n) return base[n] == true end
    local hammer = { label = 'Hammer', weight = 800, size_class = 'pocket', stackable = false, value_base = 4 }
    local wheel = { label = 'Wagon Wheel', weight = 15000, size_class = 'bulky', stackable = false, value_base = 12 }

    it('registers a valid batch under its owner, resolve finds it', function()
        Items._reset()
        local ok, err, names = Items.register({ hammer = hammer, wagon_wheel = wheel }, 'fh_roads', isBase)
        assert(ok, err)
        same({ 'hammer', 'wagon_wheel' }, names)
        eq('bulky', Items.resolve('wagon_wheel').size_class)
        eq('fh_roads', Items.ownerOf('hammer'))
    end)
    it('rejects the §4.1 schema: bad entry refuses the whole batch, nothing applied', function()
        Items._reset()
        local ok, err, bad = Items.register({ hammer = hammer, junk = { label = 'J', weight = 1, size_class = 'huge' } },
            'fh_roads', isBase)
        eq(false, ok); eq('fh_bad_size_class', err); eq('junk', bad)
        eq(nil, Items.definition('hammer'), 'nothing applied')
        eq('fh_bad_label', select(2, Items.register({ x = { weight = 1 } }, 'r', isBase)))
        eq('fh_bad_weight', select(2, Items.register({ x = { label = 'X', weight = -1 } }, 'r', isBase)))
        eq('fh_bad_value_base', select(2, Items.register({ x = { label = 'X', weight = 1, value_base = -1 } }, 'r', isBase)))
        eq('fh_item_not_table', select(2, Items.register({ x = 'nope' }, 'r', isBase)))
        eq('fh_item_not_table', select(2, Items.register('nope', 'r', isBase)))
    end)
    it('rejects bad names (rsg-inventory lowercases on remove)', function()
        Items._reset()
        for _, n in ipairs({ 'Hammer', 'wagon wheel', '', 'x-y' }) do
            local ok, err = Items.register({ [n] = hammer }, 'r', isBase)
            eq(false, ok, n); eq('fh_bad_item_name', err, n)
        end
        eq('fh_bad_item_name', select(2, Items.register({ [1] = hammer }, 'r', isBase)))
    end)
    it('rejects a duplicate of a config item', function()
        Items._reset()
        local ok, err, bad = Items.register({ gold_bar = hammer }, 'fh_roads', isBase)
        eq(false, ok); eq('fh_duplicate_item', err); eq('gold_bar', bad)
        eq('cargo', Items.resolve('gold_bar').size_class, 'config def untouched')
    end)
    it('rejects a duplicate of another resource\'s item, keeps the first', function()
        Items._reset()
        assert(Items.register({ hammer = hammer }, 'fh_roads', isBase))
        local ok, err, bad = Items.register({ hammer = wheel }, 'fh_homestead', isBase)
        eq(false, ok); eq('fh_duplicate_item', err); eq('hammer', bad)
        eq('pocket', Items.resolve('hammer').size_class); eq('fh_roads', Items.ownerOf('hammer'))
    end)
    it('a duplicate anywhere in the batch refuses the rest too', function()
        Items._reset()
        assert(Items.register({ hammer = hammer }, 'fh_roads', isBase))
        eq(false, (Items.register({ hammer = hammer, wagon_wheel = wheel }, 'fh_homestead', isBase)))
        eq(nil, Items.definition('wagon_wheel'))
    end)
    it('rejects a base rsg item name (use FhConfig.ItemOverrides)', function()
        Items._reset()
        local ok, err, bad = Items.register({ bread = hammer }, 'fh_roads', isBase)
        eq(false, ok); eq('fh_duplicate_item', err); eq('bread', bad)
    end)
    it('the same owner may re-register its own names (resource restart)', function()
        Items._reset()
        assert(Items.register({ hammer = hammer }, 'fh_roads', isBase))
        local changed = { label = 'Hammer', weight = 900, size_class = 'pocket' }
        assert(Items.register({ hammer = changed }, 'fh_roads', isBase))
        eq(900, Items.resolve('hammer').weight)
        Items._reset()
    end)
end)

T.finish()
