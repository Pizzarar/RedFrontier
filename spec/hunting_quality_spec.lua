-- Run from repo root: `lua spec/hunting_quality_spec.lua` (or via tools/run-specs.py).
local here = debug.getinfo(1, 'S').source:match('^@(.*[/\\])') or './'
local T = dofile(here .. 'support/fh_prelude.lua')
local describe, it, eq = T.describe, T.it, T.eq
local base = here .. '../server/resources/[fh]/fh_hunting/'
local cfg = dofile(base .. 'config.lua')
local Q = dofile(base .. 'shared/quality.lua')

local function never() return 0.99 end   -- rng that never downgrades
local function always() return 0.0 end   -- rng that always downgrades

local function stars(input)
    local ok, s, detail = Q.resolve(input, cfg)
    assert(ok, tostring(s))
    return s, detail
end

describe('hunting quality: config defaults', function()
    it('rolls by default', function() eq('roll', cfg.PeltQualitySource) end)
    it('ranges and multipliers', function()
        eq(5.0, cfg.SkinRange); eq(8.0, cfg.WagonRange)
        eq(0.4, cfg.QualityMult[1]); eq(1.0, cfg.QualityMult[2]); eq(1.8, cfg.QualityMult[3]); eq(4, cfg.LegendaryMult)
    end)
end)

describe('hunting quality: roll source, bone -> stars', function()
    it('head and vital bones give 3 stars', function()
        eq(3, stars({ bone = 'SKEL_Head', rng = never }))
        eq(3, stars({ bone = 'skel_neck1', rng = never }))
        eq(3, stars({ bone = 'SKEL_Spine3', rng = never }))
    end)
    it('body bones give 2 stars', function()
        eq(2, stars({ bone = 'skel_spine1', rng = never }))
    end)
    it('limb and gut bones give 1 star', function()
        eq(1, stars({ bone = 'skel_l_thigh' }))
        eq(1, stars({ bone = 'skel_r_forearm' }))
        eq(1, stars({ bone = 'skel_spine0' }))
        eq(1, stars({ bone = 'skel_pelvis' }))
    end)
    it('explosive and multi-hit give 1 star even from a head bone', function()
        eq(1, stars({ bone = 'skel_head', explosive = true }))
        eq(1, stars({ bone = 'skel_head', hits = 2 }))
        eq(3, stars({ bone = 'skel_head', hits = 1, rng = never }))
    end)
    it('an unknown bone falls back to the default zone (body, 2 stars)', function()
        local s, d = stars({ bone = 'skel_mystery', rng = never })
        eq(2, s); eq('body', d.zone)
        eq(2, stars({ rng = never }))
    end)
    it('a numeric bone id works when configured', function()
        local c = { PeltQualitySource = 'roll', MultiHitMin = 2, DefaultZone = 'body', BoneZones = { [21030] = 'head' },
            Zones = cfg.Zones, QualityMult = cfg.QualityMult }
        local ok, s = Q.resolve({ bone = 21030, rng = never }, c)
        assert(ok); eq(3, s)
    end)
end)

describe('hunting quality: roll within the band', function()
    it('the injected rng can lower a 3 star zone by one star, never below the zone floor', function()
        local s, d = stars({ bone = 'skel_head', rng = always })
        eq(2, s); eq(true, d.rolled)
        eq(1, stars({ bone = 'skel_spine1', rng = always })) -- body 2 -> 1
    end)
    it('a high roll keeps the zone stars', function()
        local s, d = stars({ bone = 'skel_head', rng = never })
        eq(3, s); eq(false, d.rolled)
    end)
    it('the roll sits exactly on the chance boundary: below downgrades, equal does not', function()
        eq(3, stars({ bone = 'skel_head', rng = function() return cfg.Zones.head.downgradeChance end }))
        eq(2, stars({ bone = 'skel_head', rng = function() return cfg.Zones.head.downgradeChance - 0.001 end }))
    end)
    it('a band that needs a roll but has no rng is refused', function()
        local ok, err = Q.resolve({ bone = 'skel_head' }, cfg)
        eq(false, ok); eq('fh_no_rng', err)
    end)
    it('a zone name can be passed directly; an unknown one is refused', function()
        eq(1, stars({ zone = 'limb' }))
        local ok, err = Q.resolve({ zone = 'toe' }, cfg)
        eq(false, ok); eq('fh_bad_zone', err)
    end)
end)

describe('hunting quality: native source', function()
    it('maps quality 0/1/2 to 1/2/3 stars', function()
        eq(1, stars({ source = 'native', nativeQuality = 0 }))
        eq(2, stars({ source = 'native', nativeQuality = 1 }))
        eq(3, stars({ source = 'native', nativeQuality = 2 }))
    end)
    it('maps cleanliness 0/1/2 to 3/2/1 stars', function()
        eq(3, stars({ source = 'native', cleanliness = 0 }))
        eq(2, stars({ source = 'native', cleanliness = 1 }))
        eq(1, stars({ source = 'native', cleanliness = 2 }))
    end)
    it('takes the lower of the two', function()
        eq(2, stars({ source = 'native', nativeQuality = 2, cleanliness = 1 }))
    end)
    it('an out-of-range value reads as 1 star', function()
        eq(1, stars({ source = 'native', nativeQuality = 9 }))
        eq(1, stars({ source = 'native', nativeQuality = 2, cleanliness = 3 }))
    end)
    it('needs at least one native value', function()
        local ok, err = Q.resolve({ source = 'native' }, cfg)
        eq(false, ok); eq('fh_no_native_quality', err)
    end)
    it('uses cfg.PeltQualitySource when the input names no source', function()
        local c = setmetatable({ PeltQualitySource = 'native' }, { __index = cfg })
        local ok, s = Q.resolve({ nativeQuality = 2 }, c)
        assert(ok); eq(3, s)
    end)
end)

describe('hunting quality: legendary and bad input', function()
    it('legendary is always 3 stars, whatever the report says', function()
        eq(3, stars({ legendary = true, bone = 'skel_l_foot', hits = 5, explosive = true }))
        eq(3, stars({ legendary = true, source = 'native', nativeQuality = 0 }))
    end)
    it('rejects non-table input and an unknown source', function()
        eq('fh_bad_input', select(2, Q.resolve(nil, cfg)))
        eq('fh_bad_source', select(2, Q.resolve({ source = 'magic' }, cfg)))
    end)
end)

describe('hunting quality: plausibility', function()
    local function good() return { dead = true, distance = 2.0, claimed = false } end
    it('accepts a dead, close, unclaimed carcass', function()
        assert(Q.plausibility(good(), cfg))
    end)
    it('accepts exactly the skin range', function()
        local c = good(); c.distance = cfg.SkinRange
        assert(Q.plausibility(c, cfg))
    end)
    it('rejects a carcass that is not dead (or unknown)', function()
        local c = good(); c.dead = false
        eq('fh_not_dead', select(2, Q.plausibility(c, cfg)))
        c.dead = nil
        eq('fh_not_dead', select(2, Q.plausibility(c, cfg)))
    end)
    it('rejects more than 5 m from the skinner, or an unreadable distance', function()
        local c = good(); c.distance = 5.01
        eq('fh_too_far', select(2, Q.plausibility(c, cfg)))
        c.distance = nil
        eq('fh_too_far', select(2, Q.plausibility(c, cfg)))
        c.distance = 0 / 0
        eq('fh_too_far', select(2, Q.plausibility(c, cfg)))
        c.distance = -1
        eq('fh_too_far', select(2, Q.plausibility(c, cfg)))
    end)
    it('rejects an already claimed carcass, first', function()
        local c = good(); c.claimed = true
        eq('fh_already_claimed', select(2, Q.plausibility(c, cfg)))
        c.dead = false
        eq('fh_already_claimed', select(2, Q.plausibility(c, cfg)))
    end)
    it('rejects a non-table check', function()
        eq('fh_bad_check', select(2, Q.plausibility(nil, cfg)))
    end)
end)

T.finish()
