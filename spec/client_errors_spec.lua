-- Run from repo root: `lua spec/client_errors_spec.lua` (or via busted / tools/run-specs.py).
local here = debug.getinfo(1, 'S').source:match('^@(.*[/\\])') or './'
local T = dofile(here .. 'support/fh_prelude.lua')
local case = T.it
local E = require('client_errors')

case('validate: accepts a good payload', function()
    local c = assert(E.validate({ resource = 'fh_homestead', msg = 'boom', traceback = 'tb' }))
    assert(c.resource == 'fh_homestead' and c.msg == 'boom' and c.traceback == 'tb')
    assert(E.validate({ resource = 'r', msg = 'm' }).traceback == '')
end)
case('validate: rejects bad shapes', function()
    local function code(p) local _, e = E.validate(p) return e end
    assert(code(nil) == 'fh_bad_payload' and code('x') == 'fh_bad_payload')
    assert(code({ msg = 'm' }) == 'fh_bad_resource' and code({ resource = '', msg = 'm' }) == 'fh_bad_resource')
    assert(code({ resource = 1, msg = 'm' }) == 'fh_bad_resource')
    assert(code({ resource = 'r', msg = 5 }) == 'fh_bad_msg')
    assert(code({ resource = 'r', msg = 'm', traceback = {} }) == 'fh_bad_traceback')
end)
case('validate: truncates and strips newlines', function()
    local c = E.validate({ resource = 'r', msg = string.rep('a', 5000), traceback = string.rep('b', 9000) })
    assert(#c.msg <= E.MAX_MSG + 3 and #c.traceback <= E.MAX_TRACEBACK + 3)
    local f = E.validate({ resource = 'r\n', msg = 'a\nb\r\tc', traceback = 'x\ny' })
    assert(not (f.resource .. f.msg .. f.traceback):find('[\r\n\t]'))
    assert(f.msg == 'a\92nb? c' and f.traceback == 'x\92ny')
end)
case('limiter: caps per source per window, then resets', function()
    local L = E.newLimiter(3, 60)
    for i = 1, 3 do assert(L.allow(7, 100 + i)) end
    assert(not L.allow(7, 110))
    assert(L.allow(8, 110), 'other source unaffected')
    assert(L.allow(7, 170), 'window elapsed')
    L.forget(7)
    assert(L.allow(7, 171))
end)
case('formatLine: single line with all fields', function()
    local line = E.formatLine('2026-11-22T00:00:00Z', 5, { resource = 'r', msg = 'm', traceback = 't' })
    assert(line == '2026-11-22T00:00:00Z src=5 resource=r msg=m traceback=t', line)
end)
T.finish()
