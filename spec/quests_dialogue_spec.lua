-- Run from repo root: `lua spec/quests_dialogue_spec.lua` (or via tools/run-specs.py).
local here = debug.getinfo(1, 'S').source:match('^@(.*[/\\])') or './'
local T = dofile(here .. 'support/fh_prelude.lua')
local case = T.it
local base = here .. '../server/resources/[fh]/fh_quests/'
local D = dofile(base .. 'shared/dialogue.lua')
local TX = dofile(base .. 'server/ui_text.lua')
local G = dofile(base .. 'shared/givers.lua')
local g = G.npc_hale

case('talk lines then intro then offer', function()
    local d = D.build(g, { { lines = { 'a', 'b' } }, offers = { 'family_hale' } })
    T.eq('Ruth Hale', d.speaker)
    T.eq(4, #d.pages)
    T.eq('a', d.pages[1]); T.eq(g.intro[1], d.pages[3])
    T.eq('family_hale', d.offer.quest_id)
    T.eq('Will you take the job?', d.offer.prompt)
end)
case('offer only: intro pages', function()
    local d = D.build(g, { offers = { 'family_hale' } })
    T.eq(#g.intro, #d.pages)
    assert(d.offer)
end)
case('offer for another quest is ignored', function()
    local d = D.build(g, { offers = { 'family_marrow' } })
    assert(d.offer == nil)
    T.eq('Nothing more to say right now.', d.pages[1])
end)
case('talk lines only: no offer, no fallback', function()
    local d = D.build(g, { { lines = { 'x' } }, offers = {} })
    T.eq(1, #d.pages); T.eq('x', d.pages[1]); assert(d.offer == nil)
end)
case('nil / empty dialogue -> fallback page', function()
    T.eq('Nothing more to say right now.', D.build(g, nil).pages[1])
    T.eq(1, #D.build(g, {}).pages)
end)
case('notices: codes map to text, unknown never leaks the raw code', function()
    local r = TX.talkRefused(g, 'fh_too_far')
    T.eq(0, #r.pages); T.eq('error', r.notice_kind); T.eq('You are too far away.', r.notice)
    T.eq('There is nobody here to talk to.', TX.talkRefused(g, 'fh_bad_npc').notice)
    T.eq('That quest is unknown.', TX.startNotice(false, 'fh_unknown_quest').notice)
    local u = TX.startNotice(false, 'weird_code')
    T.eq('Could not start that job.', u.notice); T.eq(false, u.offer)
    local ok = TX.startNotice(true)
    T.eq('Quest started.', ok.notice); T.eq('ok', ok.notice_kind); T.eq(false, ok.offer)
    assert(TX.startNotice(false, 'fh_quest_active').notice:find('already'))
end)

T.finish()
